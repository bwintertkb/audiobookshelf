def whisper_language_code(language):
    """Whisper language code for a book's metadata language ("English", "en", "en-GB", "eng"), or None if unknown"""
    value = str(language or "").strip().lower()
    if not value:
        return None
    base = value.replace("_", "-").split("-")[0]
    if base in WHISPER_LANGUAGES:
        return base
    if base in THREE_LETTER_CODES:
        return THREE_LETTER_CODES[base]
    for code, name in WHISPER_LANGUAGES.items():
        if name.lower() == value:
            return code
    return None
