/**
 * Whisper language code for a book's metadata language ("English", "en", "en-GB", "eng"), or null if unknown
 * @param {string} language
 */
export function whisperLanguageCode(language) {
  const value = String(language || '')
    .trim()
    .toLowerCase()
  if (!value) return null
  const base = value.split(/[-_]/)[0]
  if (WHISPER_LANGUAGES[base]) return base
  if (THREE_LETTER_CODES[base]) return THREE_LETTER_CODES[base]
  const byName = Object.entries(WHISPER_LANGUAGES).find(([, name]) => name.toLowerCase() === value)
  return byName ? byName[0] : null
}
